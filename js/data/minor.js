function fileNameFor(suitKey, rank) {
  const n = typeof rank === 'number' ? rank : FILE_NUM[rank];
  return `${SUITS[suitKey].prefix}${String(n).padStart(2, '0')}.jpg`;
}

function idFor(suitKey, rank) {
  const letter = { wands: 'w', cups: 'c', swords: 's', pentacles: 'p' }[suitKey];
  const n = typeof rank === 'number' ? rank : FILE_NUM[rank];
  return `${letter}${String(n).padStart(2, '0')}`;
}

export const MINOR = Object.entries(RAW).flatMap(([suitKey, rows]) => {
  const suit = SUITS[suitKey];
  return rows.map(([rank, keyUp, keyRev, up, rev]) => ({
    id: idFor(suitKey, rank),
    nameKo: `${suit.ko} ${RANK_KO[rank]}`,
    nameEn: `${RANK_EN[rank]} of ${suit.en}`,
    arcana: 'minor',
    suit: suitKey,
    rank,
    num: typeof rank === 'number' ? rank : FILE_NUM[rank],
    element: suit.element,
    file: fileNameFor(suitKey, rank),
    svg: suit.glyph,
    keyUp, keyRev, up, rev
  }));
});
